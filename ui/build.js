// Bundles ui/spectrum.js into web-src/spectrum.<hash>.js (served by App Builder static hosting)
// and records its file name in actions/mcp-server/spectrum-asset.js for the views.
const path = require('path')
const fs = require('fs')
const crypto = require('crypto')
const esbuild = require('esbuild')

const WEB_SRC = path.join(__dirname, '..', 'web-src')
const ASSET_MODULE = path.join(__dirname, '..', 'actions', 'mcp-server', 'spectrum-asset.js')

function buildUi () {
  const result = esbuild.buildSync({
    entryPoints: [path.join(__dirname, 'spectrum.js')],
    bundle: true,
    minify: true,
    format: 'esm',
    target: 'es2020',
    legalComments: 'none',
    write: false
  })
  const code = result.outputFiles[0].text
  const hash = crypto.createHash('sha256').update(code).digest('hex').slice(0, 12)
  const fileName = `spectrum.${hash}.js`

  fs.mkdirSync(WEB_SRC, { recursive: true })
  for (const old of fs.readdirSync(WEB_SRC).filter(f => /^spectrum\.[0-9a-f]+\.js$/.test(f))) {
    fs.rmSync(path.join(WEB_SRC, old))
  }
  fs.writeFileSync(path.join(WEB_SRC, fileName), code)
  fs.writeFileSync(ASSET_MODULE, `// Generated by ui/build.js, do not edit.\nmodule.exports = ${JSON.stringify({ fileName })}\n`)
  console.log(`web-src/${fileName}: ${(code.length / 1024).toFixed(0)} KB`)
  return fileName
}

if (require.main === module) buildUi()

module.exports = { buildUi, WEB_SRC }
